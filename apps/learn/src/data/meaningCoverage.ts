const MONTHS = new Set<string>(["JANUARY","FEBRUARY","MARCH","APRIL","MAY","JUNE","JULY","AUGUST","SEPTEMBER","OCTOBER","NOVEMBER","DECEMBER"])

export function isMeaningVerified(gloss: string): boolean {
  return Boolean(translationOf(gloss))
}

export function isSelfExplaining(gloss: string): boolean {
  const clean = gloss.trim().toUpperCase()
  return /^[A-Z]$/.test(clean) || /^\d+$/.test(clean) || MONTHS.has(clean)
}

/** Display coverage only: an English filename is not a verified translation. */
export function hasMeaningCoverage(gloss: string): boolean {
  return isMeaningVerified(gloss) || isSelfExplaining(gloss) || ENGLISH_DATASET_NAMES.has(gloss.trim().toUpperCase())
}

/** Stable partition preserves the corpus order; months keep calendar order. */
export function orderSignsVerifiedFirst<T extends { gloss: string }>(category: string, signs: T[]): T[] {
  const ordered = orderSigns(category, signs)
  return [
    ...ordered.filter(sign => hasMeaningCoverage(sign.gloss)),
    ...ordered.filter(sign => !hasMeaningCoverage(sign.gloss)),
  ]
}
